#!/usr/bin/env -S npx tsx
/**
 * Render the OTSM Network of Problems as a markdown report with a Mermaid graph,
 * the TOC core-conflict, coupled clusters, and the DIKWP purpose table.
 *
 *   TRIZ_GRAPH=examples/problem-graph.json npx tsx scripts/graph-report.mjs [out.md]
 */
import fs from "node:fs";
import path from "node:path";
import { analyse, loadGraph, resolveGraphPath } from "../src/graph.js";

const graphSource = resolveGraphPath();
const a = analyse();
const { edges } = loadGraph();
const core = a.coreConflict[0];

const mermaid = [
  "```mermaid",
  "graph LR",
  ...a.nodes.map((n) => `  ${n.id}["${n.id} §${n.section}<br/>${n.title}"]`),
  ...edges.map((e) => {
    const arrow = e.type === "dissolves" ? "==>" : e.type === "blocks" ? "-.->" : "---";
    return `  ${e.from} ${arrow}|${e.type}| ${e.to}`;
  }),
  `  style ${core.id} fill:#f9d,stroke:#c06,stroke-width:3px`,
  "```",
].join("\n");

const purposeTable = [
  "| Node | § | Contradiction | Purpose (invariant served) | Bound spec | Purpose secured? |",
  "|------|---|---------------|----------------------------|-----------|:---:|",
  ...a.nodes.map((n) =>
    `| ${n.id} | ${n.section} | ${n.title} | ${n.purpose} | ${n.spec ? "`" + n.spec.split("/").pop() + "`" : "—"} | ${n.purpose_secured ? "✅" : "❌"} |`),
].join("\n");

const md = `# TRIZ Problem-Graph — OTSM Network of Problems + DIKWP Purpose Layer

> Generated by \`scripts/graph-report.mjs\` from \`${path.relative(process.cwd(), graphSource)}\`.
> Do not hand-edit; edit the graph data and regenerate.

## TOC core conflict

**${core.id} — ${core.title}** dissolves ${core.dissolves.length} other contradiction(s): ${core.dissolves.join(", ") || "none"}.
Per C-TRIZ's Theory-of-Constraints step, **attack this one first** — resolving it removes the most others.

Ranking (by dissolves-out-degree, then coupling):
${a.coreConflict.map((c, i) => `${i + 1}. ${c.id} — dissolves [${c.dissolves.join(", ") || "—"}], couples ${c.couples}`).join("\n")}

## Coupled clusters (components over \`couples\` edges)

${a.clusters.length ? a.clusters.map((c) => `- { ${c.join(", ")} }`).join("\n") : "- (none)"}

## Network

${mermaid}

Legend: \`==>\` dissolves · \`---\` couples · \`-.->\` blocks. Pink node = core conflict.

## DIKWP purpose layer

A purpose is **secured** only when its bound formal invariant is verifier-backed (a linked
registry entry carries a \`verified_by\` record). Closing a verify→repair loop flips this automatically.

${purposeTable}

**Secured: ${a.nodes.filter((n) => n.purpose_secured).length} / ${a.nodes.length}.** ${
  a.nodes.every((n) => n.purpose_secured)
    ? "Every open-contradiction purpose is verifier-backed. Check what each `verified_by` record actually establishes — a bounded model check is not an unconditional proof."
    : "The rest are the work queue — bind a formal invariant, then close the verify→repair loop to secure the purpose."
}
`;

const out = path.resolve(process.cwd(), process.argv[2] ?? "problem-graph.md");
fs.writeFileSync(out, md);
console.error(`wrote ${out}: core=${core.id}, clusters=${a.clusters.length}, secured=${a.nodes.filter((n) => n.purpose_secured).length}/${a.nodes.length}`);
