#!/usr/bin/env node
/** Validate every installed pack and generate static imports for the hosted runtime. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { KnowledgeManifest, compileKnowledge } from "../src/knowledge.ts";
import { CanonicalParameters } from "../src/parameters.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const data = path.join(root, "skills/triz-innovation/data");
const read = file => JSON.parse(fs.readFileSync(path.join(data, file), "utf8"));
const canonical = CanonicalParameters.parse(read("parameters.json"));
const manifest = KnowledgeManifest.parse(read("knowledge.json"));
const knowledge = compileKnowledge(manifest.packs.map(read));
const files = ["knowledge.json", ...manifest.packs];
const source = "// Generated by scripts/knowledge.mjs; edit the manifest and packs, then run pnpm knowledge.\n" +
  files.map((file, i) => `import data${i} from ${JSON.stringify(`../skills/triz-innovation/data/${file}`)} with { type: "json" };`).join("\n") +
  "\nexport const bundledKnowledge: Record<string, unknown> = {\n" +
  files.map((file, i) => `  ${JSON.stringify(file)}: data${i},`).join("\n") + "\n};\n";
const target = path.join(root, "src/knowledge-bundle.ts");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== source)
    throw new Error("Hosted knowledge imports are stale; run pnpm knowledge");
} else fs.writeFileSync(target, source);
console.log(`Knowledge valid: ${canonical.parameters.length} canonical matrix parameters; ${knowledge.packs.length} packs, ${knowledge.parameters.length} quantity parameters, ${knowledge.effects.length} searchable effects; ${knowledge.counts.independent_contracts} independent interfaces, ${knowledge.counts.specializations} specializations, ${knowledge.counts.composites} serial recipes, ${knowledge.counts.configurations} named model configurations`);
